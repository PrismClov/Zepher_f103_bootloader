# Release build: inject production VID/PID and optionally sign the host tool.
#
# Usage:
#   .\build-release.ps1 -Vid 0x1234 -Pid 0x5678
#   .\build-release.ps1 -Vid 0x1234 -Pid 0x5678 `
#       -SignTool "C:\Program Files (x86)\Windows Kits\10\bin\x64\signtool.exe" `
#       -CertPath ".\certs\release.pfx" -CertPassword "******"
#
# WARNING: 0x1209:0xF103 is a prototype PID. Never ship it.

param(
    [Parameter(Mandatory = $true)][string]$UsbVid,
    [Parameter(Mandatory = $true)][string]$UsbPid,
    [string]$SignTool = "",
    [string]$CertPath = "",
    [string]$CertPassword = ""
)

$ErrorActionPreference = "Stop"

if ($UsbVid -notmatch '^0x[0-9A-Fa-f]{4}$' -or $UsbPid -notmatch '^0x[0-9A-Fa-f]{4}$') {
    throw "Vid/Pid must look like 0x1234"
}

$ProjectRoot = $PSScriptRoot
$Workspace = Join-Path $ProjectRoot "zephyrproject"
$West = Join-Path $ProjectRoot ".venv\Scripts\west.exe"
$Gcc = Get-Command arm-none-eabi-gcc -ErrorAction Stop
$ToolchainRoot = Split-Path (Split-Path $Gcc.Source -Parent) -Parent
$ReleaseDir = Join-Path $ProjectRoot "dist\release"
$ConfDir = Join-Path $ProjectRoot "build\release"
New-Item -ItemType Directory -Path $ReleaseDir -Force | Out-Null
New-Item -ItemType Directory -Path $ConfDir -Force | Out-Null

$ReleaseConf = Join-Path $ConfDir "release.conf"
@"
# Generated by build-release.ps1 - do not edit
CONFIG_USB_DEVICE_VID=$UsbVid
CONFIG_USB_DEVICE_PID=$UsbPid
"@ | Set-Content -Path $ReleaseConf -Encoding ASCII

$env:ZEPHYR_BASE = Join-Path $Workspace "zephyr"
$env:ZEPHYR_TOOLCHAIN_VARIANT = "gnuarmemb"
$env:GNUARMEMB_TOOLCHAIN_PATH = $ToolchainRoot

Push-Location $Workspace
try {
    & $West build -p always -b stm32_min_dev $ProjectRoot `
        -d (Join-Path $ProjectRoot "build\release-bootloader") `
        -- "-DEXTRA_CONF_FILE=$ReleaseConf"
    if ($LASTEXITCODE -ne 0) { throw "Bootloader release build failed." }

    & $West build -p always -b stm32_min_dev (Join-Path $ProjectRoot "app_template") `
        -d (Join-Path $ProjectRoot "build\release-app") `
        -- "-DEXTRA_CONF_FILE=$ReleaseConf"
    if ($LASTEXITCODE -ne 0) { throw "Application release build failed." }
}
finally {
    Pop-Location
}

Copy-Item (Join-Path $ProjectRoot "build\release-bootloader\zephyr\zephyr.hex") `
    (Join-Path $ReleaseDir "f103_usb_bootloader.hex") -Force
Copy-Item (Join-Path $ProjectRoot "build\release-bootloader\zephyr\zephyr.bin") `
    (Join-Path $ReleaseDir "f103_usb_bootloader.bin") -Force
Copy-Item (Join-Path $ProjectRoot "build\release-app\zephyr\zephyr.hex") `
    (Join-Path $ReleaseDir "app_template.hex") -Force
Copy-Item (Join-Path $ProjectRoot "build\release-app\zephyr\zephyr.bin") `
    (Join-Path $ReleaseDir "app_template.bin") -Force

Write-Host "Release firmware written to $ReleaseDir"
Write-Host "  VID=$UsbVid PID=$UsbPid"

if ($SignTool -and $CertPath -and $CertPassword) {
    foreach ($exe in @("F103_USB_Updater.exe", "f103_uploader.exe")) {
        $target = Join-Path $ProjectRoot "dist\$exe"
        if (-not (Test-Path $target)) { continue }
        & $SignTool sign /f $CertPath /p $CertPassword /fd SHA256 `
            /tr http://timestamp.digicert.com /td SHA256 $target
        if ($LASTEXITCODE -ne 0) { throw "Signing failed for $exe" }
        Copy-Item $target (Join-Path $ReleaseDir $exe) -Force
    }
    Write-Host "Host tools signed and copied to $ReleaseDir"
} else {
    Write-Warning "SignTool/CertPath/CertPassword not provided: host tools are unsigned."
}
